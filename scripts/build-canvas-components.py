texts = [io.open(p, encoding='utf-8').read() for p in sorted(glob.glob(os.path.join(src, '*.dc.html')))]
icon_svgs, ill_svgs = [], []
for text in texts:
    for m in re.finditer(r'<svg[^>]*viewBox="0 0 24 24"[^>]*>(.*?)</svg>', text, re.S):
        icon_svgs.append(re.sub(r'\s+', ' ', m.group(1)).strip())
    for m in re.finditer(r'<svg[^>]*viewBox="0 0 120 120"[^>]*>(.*?)</svg>', text, re.S):
        after = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', text[m.end():m.end() + 200]))
        ill_svgs.append((re.sub(r'\s+', ' ', m.group(1)).strip(), after))


def tokenise(markup: str) -> str:
    """Replace fill/stroke hex attributes with token classes."""
    def element(m):
        tag = m.group(0)
        classes = []
        for attr in ('fill', 'stroke'):
            am = re.search(attr + r'="(#[0-9A-Fa-f]{6})"', tag)
            if am:
                token = TOKENS[am.group(1).upper()]
                classes.append(f'{attr}-{token}')
                tag = tag.replace(am.group(0), '')
        if classes:
            tag = re.sub(r'^<(\w+)', lambda t: f'<{t.group(1)} class="{" ".join(classes)}"', tag)
        return re.sub(r'\s+(/?>)$', r'\1', re.sub(r' {2,}', ' ', tag))
    out = re.sub(r'<\w+[^>]*>', element, markup)
    left = re.findall(r'#[0-9A-Fa-f]{6}', out)
    if left:
        raise SystemExit(f'unmapped colours: {left}')
    return out


icons = {}
for name, frag in ICONS.items():
    match = next((s for s in icon_svgs if frag in s), None)
    if match is None:
        raise SystemExit(f'icon not found: {name}')
    icons[name] = match.replace('stroke="#E8A33D"', '').replace('stroke="#A8A6B3"', '')

ills = {}
for name, cue in ILLUSTRATIONS.items():
    match = next((s for s, after in ill_svgs if cue in after), None)
    if match is None:
        raise SystemExit(f'illustration not found: {name}')
    ills[name] = tokenise(match)


def php_map(d):
    lines = []
    for k in sorted(d):
        v = d[k].replace('\\', '\\\\').replace("'", "\\'")
        lines.append(f"        '{k}' => '{v}',")
    return '\n'.join(lines)


