"""Generate <x-icon> and <x-illustration> Blade components from the screens canvas.

Icons: the canvas's 24px stroke icons. Illustrations: its 120px spot drawings, with every
hex colour replaced by a design-system token class (fill-*/stroke-*), so views hold no hex.
"""
import glob
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding='utf-8')
src, repo = sys.argv[1], sys.argv[2]

TOKENS = {
    '#0B0B0F': 'bg', '#15151C': 'surface', '#1E1E28': 'surface-raised', '#2E2E3A': 'border',
    '#6B6978': 'border-strong', '#F5F3EF': 'ink', '#A8A6B3': 'ink-muted', '#E8A33D': 'brand',
    '#1A1206': 'on-brand', '#34C47C': 'success', '#F5D06B': 'warning', '#F0525B': 'danger',
    '#B97A22': 'illustration-shade', '#F5C877': 'illustration-highlight',
}

